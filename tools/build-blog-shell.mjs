// Builds api/_lib/blog-shell.js from scoop-shell.html (the site header and footer around the blog).
// Run after changing the site header or footer:  node tools/build-blog-shell.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
let html = fs.readFileSync(path.join(root, 'tools/scoop-shell.html'), 'utf8');

// Head: keep everything except page-specific title and meta tags.
html = html.replace(/<title>[\s\S]*?<\/title>/, '{{HEAD}}')
  .replace(/\s*<meta name="description"[^>]*>/, '')
  .replace(/\s*<meta name="keywords"[^>]*>/, '')
  .replace(/\s*<meta property="og:[^>]*>/g, '')
  .replace(/\s*<meta name="twitter:card"[^>]*>/, '');
html = html.replace(/<main[\s\S]*?<\/main>/, '{{MAIN}}');
// Use the same cache-busting version as the rest of the site.
const v = (fs.readFileSync(path.join(root, 'index.html'), 'utf8').match(/\?v=([0-9a-z]+)"/) || [])[1];
if (v) html = html.replace(/\?v=[0-9a-z]+"/g, `?v=${v}"`);
// Blog pages live at /scoop/..., so make every relative link start from the site root.
html = html.replace(/(href|src)="(?!https?:|\/|#|mailto:|tel:|data:|\{)([^"]*)"/g, '$1="/$2"')
  .replace(/url\('(?!https?:|\/|data:)([^']*)'\)/g, "url('/$1')");

fs.writeFileSync(path.join(root, 'api/_lib/blog-shell.js'),
  '// Generated by tools/build-blog-shell.mjs from tools/scoop-shell.html. Do not edit by hand.\nexport const SHELL = ' + JSON.stringify(html) + ';\n');
console.log('Wrote api/_lib/blog-shell.js', html.length, 'chars');
